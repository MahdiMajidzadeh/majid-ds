<?php

/*
|--------------------------------------------------------------------------
| Static site builder for GitHub Pages
|--------------------------------------------------------------------------
|
| The reference docs are generated by bin/build-docs.php — including the Demo
| pages, which embed the workbench's demo cards directly. The layout gallery,
| though, only exists as full pages rendered by the testbench workbench app.
| This script boots that app on a throwaway port, crawls every layout page,
| and writes the result into docs/demo/ as flat .html files.
|
| Everything lands flat inside docs/demo/: /demo -> demo.html, /layouts/aside ->
| layouts-aside.html, and the English routes take an -en suffix: /en/demo ->
| demo-en.html. Flat siblings mean a single relative rewrite ("/layouts/aside" ->
| "layouts-aside.html") is correct on every page — no depth arithmetic — and the
| demo/ directory keeps the docs root to the reference pages, so the site works
| under a project subpath as well as straight off the file system.
|
|   php bin/build-pages.php [--port=8799] [--skip-css]
|
*/

$root = dirname(__DIR__);
chdir($root);

$options = getopt('', ['port::', 'skip-css', 'help']) ?: [];

if (isset($options['help'])) {
    fwrite(STDOUT, "Usage: php bin/build-pages.php [--port=8799] [--skip-css]\n");
    exit(0);
}

$port = (int) ($options['port'] ?? 8799);
$out = $root.'/docs/demo';
$assets = $root.'/docs/assets';
$origin = 'http://127.0.0.1:'.$port;

/** Entry points; everything else is discovered by following links. */
$entryPoints = ['/layouts', '/en/layouts'];

/*
| The demo routes stay live for `npm run demo:serve`, but their static homes
| are the Demo / RTL demo pages inside the docs — so the crawl skips them and
| the layout pages' links to them are rewritten to point there instead.
*/
$external = [
    '/demo' => '../guides/rtl-demo.html',
    '/en/demo' => '../guides/demo.html',
];

function info(string $message): void
{
    fwrite(STDOUT, $message."\n");
}

function fail(string $message): never
{
    fwrite(STDERR, 'error: '.$message."\n");
    exit(1);
}

function get(string $url, int $timeout = 30): ?string
{
    $context = stream_context_create(['http' => ['timeout' => $timeout, 'ignore_errors' => true]]);
    $body = @file_get_contents($url, false, $context);

    if ($body === false) {
        return null;
    }

    $status = (int) (explode(' ', $http_response_header[0] ?? 'HTTP/1.1 000')[1] ?? 0);

    return $status === 200 ? $body : null;
}

/**
 * '/demo' -> 'demo.html', '/layouts/aside' -> 'layouts-aside.html', and the
 * locale moves from prefix to suffix so the pair sorts together in a listing:
 * '/en/demo' -> 'demo-en.html'.
 */
function filenameFor(string $path): string
{
    $trimmed = trim($path, '/');
    $locale = '';

    if ($trimmed === 'en' || str_starts_with($trimmed, 'en/')) {
        $trimmed = substr($trimmed, 2);
        $locale = '-en';
    }

    $trimmed = trim($trimmed, '/');

    return $trimmed === '' ? 'index'.$locale.'.html' : str_replace('/', '-', $trimmed).$locale.'.html';
}

if (! is_file($root.'/vendor/autoload.php')) {
    fail('composer dependencies are missing — run `composer install` first.');
}

// ---------------------------------------------------------------- 1. demo.css

if (! isset($options['skip-css'])) {
    info('Building demo.css…');
    exec('npm run --silent demo:css 2>&1', $cssOutput, $cssStatus);

    if ($cssStatus !== 0) {
        fail("`npm run demo:css` failed:\n".implode("\n", $cssOutput));
    }
}

$demoCss = @file_get_contents($root.'/workbench/public/demo.css');

if ($demoCss === false) {
    fail('workbench/public/demo.css is missing — run without --skip-css.');
}

// ------------------------------------------------------------ 2. serve locally

info('Starting the workbench app on port '.$port.'…');

$server = proc_open(
    ['vendor/bin/testbench', 'serve', '--port='.$port, '--no-reload'],
    [1 => ['file', '/dev/null', 'w'], 2 => ['pipe', 'w']],
    $pipes,
    $root,
    // The demo's "docs" link has no route on the dev server, so it points at the
    // published page by default; in the static build the docs root is one level up.
    // MDS_TEST_NOW freezes the server's clock (see routes/web.php) so the crawled
    // pages are byte-identical across rebuilds.
    ['MDS_DOCS_HREF' => '../index.html', 'MDS_TEST_NOW' => '2026-08-24 10:00:00'] + getenv(),
);

if (! is_resource($server)) {
    fail('could not start `vendor/bin/testbench serve`.');
}

register_shutdown_function(function () use ($server, $port) {
    if (is_resource($server)) {
        proc_terminate($server);
        proc_close($server);
    }

    // testbench serve runs `php -S` in a child process that outlives the parent.
    exec(sprintf('lsof -ti tcp:%d 2>/dev/null | xargs kill 2>/dev/null', $port));
});

$ready = false;

for ($attempt = 0; $attempt < 60; $attempt++) {
    if (get($origin.$entryPoints[0], 5) !== null) {
        $ready = true;
        break;
    }

    usleep(500_000);
}

if (! $ready) {
    fail("the server never answered on {$origin}{$entryPoints[0]}:\n".stream_get_contents($pipes[2]));
}

// ------------------------------------------------------------------- 3. crawl

$pages = [];
$queue = $entryPoints;

while ($queue !== []) {
    $path = array_shift($queue);

    if (isset($pages[$path]) || isset($external[$path])) {
        continue;
    }

    $html = get($origin.$path);

    if ($html === null) {
        info('  skipped '.$path.' (not 200)');
        continue;
    }

    $pages[$path] = $html;
    info('  fetched '.$path);

    preg_match_all('~\shref="(/[^"#?]*)"~', $html, $matches);

    foreach (array_unique($matches[1]) as $link) {
        // Routes only: no asset paths, and nothing already fetched.
        if (! str_contains(basename($link), '.') && ! isset($pages[$link])) {
            $queue[] = $link;
        }
    }
}

if ($pages === []) {
    fail('nothing was crawled.');
}

// ------------------------------------------------- 4. pull the script bundles

$scriptMap = [];

if (! is_dir($assets)) {
    mkdir($assets, 0755, true);
}

foreach ($pages as $html) {
    preg_match_all('~\ssrc="('.preg_quote($origin, '~').'/[^"]+)"~', $html, $matches);

    foreach (array_unique($matches[1]) as $url) {
        if (isset($scriptMap[$url])) {
            continue;
        }

        $name = basename(parse_url($url, PHP_URL_PATH));
        $body = get($url, 60);

        if ($body === null) {
            fail('could not download '.$url);
        }

        file_put_contents($assets.'/'.$name, $body);
        $scriptMap[$url] = '../assets/'.$name;
        info('  vendored assets/'.$name.' ('.round(strlen($body) / 1024).' KB)');
    }
}

// ----------------------------------------------------------------- 5. rewrite


// Longest paths first, so '/layouts/aside' is never eaten by '/layouts'.
$paths = array_keys($pages);
usort($paths, fn ($a, $b) => strlen($b) <=> strlen($a));

$linkMap = [];

foreach ($paths as $path) {
    $linkMap['"'.$path.'"'] = '"'.filenameFor($path).'"';
}

foreach ($external as $path => $target) {
    $linkMap['"'.$path.'"'] = '"'.$target.'"';
}

if (! is_dir($out)) {
    mkdir($out, 0755, true);
}

$written = 0;

foreach ($pages as $path => $html) {
    // The layouts inline the compiled CSS with file_get_contents; link the shared
    // stylesheet instead so it is stored and downloaded once rather than per page.
    $html = str_replace('<style>'.$demoCss.'</style>', '<link rel="stylesheet" href="../assets/site.css">', $html);

    $html = strtr($html, $scriptMap);
    $html = strtr($html, $linkMap);

    // Livewire stamps its endpoint on the script tag as an absolute URL. Nothing
    // on these pages is a Livewire component, so the endpoint is never called —
    // but make it relative anyway rather than ship a localhost URL that would
    // point a visitor's browser back at their own machine.
    $html = str_replace($origin.'/', '', $html);

    // The CSRF token on that same script tag is random per crawl and equally
    // unused on a static page — pin it so rebuilds are byte-identical.
    $html = preg_replace('/\sdata-csrf="[^"]*"/', ' data-csrf="static"', $html);

    if (str_contains($html, $origin)) {
        info('  warning: '.$path.' still references '.$origin);
    }

    /*
    | The English pages are only as translated as workbench/lang/en.json is, so
    | count what is left. A handful is expected — see the note below — but a jump
    | means a string was added to a view without a translation to go with it.
    */
    if (str_starts_with($path, '/en/') && preg_match_all('/[\x{0600}-\x{06FF}]+/u', strip_tags($html), $found)) {
        $words = array_unique($found[0]);
        info(sprintf('  %d Persian strings left in %s: %s', count($words), $path, implode(' ', array_slice($words, 0, 12))));
    }

    $file = $out.'/'.filenameFor($path);

    if (@file_put_contents($file, $html) === false) {
        fail('could not write '.$file);
    }

    $written++;
    info('  wrote '.basename($file).' ('.round(strlen($html) / 1024).' KB)');
}

// Keep GitHub Pages from running the output through Jekyll.
touch($root.'/docs/.nojekyll');

/*
| The shared stylesheet is built by bin/build-docs.php, whose input scans these
| freshly written pages too — remind rather than silently ship a stale file.
*/
if (! is_file($assets.'/site.css')) {
    info('  note: docs/assets/site.css is missing — run `npm run docs` (or `npm run css`).');
}

info(sprintf('Done — %d pages in docs/demo/. Open docs/demo/layouts.html.', $written));
